"""Extract DASMx opcode tables from Dasmx.exe into C source for DASMy.

Usage: python3 -I re/scripts/gentables.py original/Dasmx.exe dasmy/src/tables

Each table is an array of 20-byte entries:
    { const char *mnemonic, const char *operands, uint32 flags, uint32 length, uint32 cycles }
"""

import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from pe import PE

# name -> (VA, number of entries)
TABLES = {
    'm6800': [('tab_6800', 0x421168, 256), ('tab_6801', 0x4225d8, 256), ('tab_6301', 0x4239f8, 256)],
    'm6805': [('tab_6805', 0x424e18, 256), ('tab_68hc05', 0x428a18, 256), ('tab_63l05', 0x426218, 256),
              ('tab_6305', 0x427618, 256)],
    'm6809': [('tab_6809', 0x41d230, 256), ('tab_6809_p10', 0x41e630, 256), ('tab_6809_p11', 0x41fa30, 256)],
    'i8080': [('tab_8080', 0x417b18, 256), ('tab_8085', 0x418f18, 256)],
    'z80': [('tab_z80', 0x432138, 256), ('tab_z80_cb', 0x435d38, 256), ('tab_z80_ed', 0x439938, 256),
            ('tab_z80_dd', 0x433538, 256), ('tab_z80_fd', 0x434938, 256),
            ('tab_z80_ddcb', 0x437138, 256), ('tab_z80_fdcb', 0x438538, 256)],
    'lr35902': [('tab_lr35902', 0x414ed0, 256), ('tab_lr35902_cb', 0x4162d0, 256)],
    'i8048': [('tab_8048', 0x41bb70, 256)],
    'i8051': [('tab_8051', 0x41a498, 256)],
    'pic16': [('tab_pic16', 0x413968, 128), ('tab_pic16_00', 0x414368, 128)],
    's2650': [('tab_2650', 0x42dcc0, 256)],
    'r1802': [('tab_1802', 0x42f710, 256), ('tab_1805_68', 0x430b10, 256)],
    'm6502': [('tab_6502', 0x429f68, 256), ('tab_65c00', 0x42b368, 256), ('tab_65c02', 0x42c768, 256)],
}


# name -> list of (array name, VA, count) for signed byte arrays
# name -> list of (array name, VA, count) for arrays of string pointers (NULL allowed)
STRING_ARRAYS = {
    's2650': [('s2650_index_regs', 0x43e1c0, 4)],
    'i8051': [('m8051_bit_names', 0x43d348, 256), ('m8051_sfr_names', 0x43d748, 256)],
}

BYTE_ARRAYS = {
    'm6809': [('m6809_index_extra', 0x41d130, 256)],
}


def c_str(s):
    if s is None:
        return 'NULL'
    out = ''.join(c if c not in '"\\' else '\\' + c for c in s)
    return f'"{out}"'


def emit(pe, out_dir, group, tables):
    path = os.path.join(out_dir, f'{group}_tab.c')
    with open(path, 'w') as f:
        f.write('/* Generated by re/scripts/gentables.py from Dasmx.exe - do not edit */\n\n')
        f.write('#include "../dasmy.h"\n')
        for name, va, count in tables:
            f.write(f'\nconst OpEntry {name}[{count}] = {{\n')
            for i in range(count):
                e = va + 20 * i
                mn, ops, flags, length, cycles = (pe.u32(e + 4 * k) for k in range(5))
                f.write(f'    /* {i:02X} */ {{ {c_str(pe.cstr(mn))}, {c_str(pe.cstr(ops))}, '
                        f'0x{flags:04X}, {length}, 0x{cycles:X} }},\n')
            f.write('};\n')
        for name, va, count in STRING_ARRAYS.get(group, []):
            f.write(f'\nconst char *const {name}[{count}] = {{\n')
            for i in range(count):
                p = pe.u32(va + 4 * i)
                f.write(f'    /* {i:02X} */ {c_str(pe.cstr(p) if p else None)},\n')
            f.write('};\n')
        for name, va, count in BYTE_ARRAYS.get(group, []):
            data = pe.bytes(va, count)
            f.write(f'\nconst signed char {name}[{count}] = {{\n')
            for i in range(0, count, 16):
                f.write('    ' + ' '.join(f'{(b ^ 0x80) - 0x80:2d},' for b in data[i:i + 16]) + f' /* {i:02X} */\n')
            f.write('};\n')
    print(f'wrote {path}')


def main():
    pe = PE(sys.argv[1])
    out_dir = sys.argv[2]
    os.makedirs(out_dir, exist_ok=True)
    for group, tables in TABLES.items():
        emit(pe, out_dir, group, tables)


if __name__ == '__main__':
    main()
